import type { Effect, EventChoice, GameEvent } from '../../src/types/content';

function decide(text: string, result: string, ...effects: Effect[]): EventChoice {
  return { text: { th: text }, outcomes: [{ text: { th: result }, effects }] };
}

const flag = (name: string): Effect => ({ kind: 'flag', flag: name });
const cash = (value: number): Effect => ({ kind: 'add', stat: 'cleanCash', value });
const fame = (value: number): Effect => ({ kind: 'add', stat: 'fame', value });
const cool = (value: number): Effect => ({ kind: 'add', stat: 'heat', value: -value });

function milestone(day: number, title: string, body: string, imageDescription: string, choices: EventChoice[]): GameEvent {
  return { id: 'life_turn_' + day, lifeStory: true, lifeMilestone: day, category: 'lucky', weight: 1,
    illustration: { scene: 'life_turn_' + day, title, alt: imageDescription },
    when: { day: [day, day + 12] }, title: { th: title }, body: { th: body }, choices };
}

