function choice(label: string, result: string, effects: Effect[]): EventChoice {
  return { text: { th: label }, outcomes: [{ text: { th: result }, effects }] };
}

const styles = [
  { name: 'สัญญาจ้าง', solo: 'รับงานรอบพิเศษด้วยตัวเอง', crew: 'ชวนทีมมารับงานด้วยกัน', soloNext: 'ใบจองรอบพิเศษ', crewNext: 'ส่วนแบ่งรอบแรก', skill: 'contract', stat: 'cleanCash', gain: 380 },
  { name: 'เสียงจากคนดู', solo: 'ขึ้นเวทีเล่าเรื่องด้วยตัวเอง', crew: 'ให้เจ้าของเรื่องขึ้นเวที', soloNext: 'คำถามหลังไมค์', crewNext: 'เสียงปรบมือของมือใหม่', skill: 'host', stat: 'fame', gain: 3 },
  { name: 'งานหลังฉาก', solo: 'อยู่แก้ปัญหาจนปิดงาน', crew: 'ให้ลูกมือลองรับช่วงต่อ', soloNext: 'กุญแจชุดสุดท้าย', crewNext: 'เวรแรกที่ไม่มีคุณ', skill: 'mentor', stat: 'heat', gain: -4 },
] as const;

function next(id: string): Effect {
  return { kind: 'schedule', eventId: id, inDays: 1 };
}

function episodes(story: Story): GameEvent[] {
  const root = 'life_' + story.id;
  const events: GameEvent[] = [];
  const open: EventChoice[] = [];
  const scene = (id: string, title: string, body: string, choices: EventChoice[]): GameEvent => ({
    id, title: { th: title }, body: { th: body }, choices,
    illustration: { scene: root, title: story.title, alt: story.imageDescription },
    lifeStory: true, chainOnly: id !== root, category: 'silly', weight: 1,
    when: { day: [story.fromDay, 90] },
  });
  story.paths.forEach(([action, consequence], index) => {
    const style = styles[index];
    if (!style) throw Error('Missing life story style for ' + root);
    const branch = root + '_' + style.skill;
    const reward: Effect = { kind: 'add', stat: style.stat, value: style.gain };
    open.push(choice(action, consequence, [reward, next(branch)]));
    const followup = scene(branch, consequence, `เมื่อครั้งก่อนคุณเลือก “${action}” คราวนี้จะลงมือเองหรือชวนคนมาช่วย?`, [
      choice(style.solo, `คุณขอจัดการเอง ผู้จัดจดชื่อคุณไว้แล้ว`, [next(branch + '_solo')]),
      choice(style.crew, `ทีมรับช่วงต่อและตกลงว่าจะกลับมารายงานผล`, [next(branch + '_crew')]),
      choice('ปิดงานเท่านี้ คืนเวลาให้ตัวเอง', 'คุณส่งต่องานที่เหลือแล้วกลับไปพัก', [{ kind: 'add', stat: 'heat', value: -2 }]),
    ]);
    events.push(followup);
    if (story.fromDay >= 31) {
      followup.choices.push({
        ...choice('ใช้ประสบการณ์หน้าเวที เปิดไมค์ให้คนดู', 'เสียงจากคนดูช่วยให้ทีมได้ชื่อเสียงและค่าจัดเวที',
          [{ kind: 'add', stat: 'fame', value: 3 }, { kind: 'add', stat: 'cleanCash', value: 250 }, next(branch + '_crew')]),
        requires: { flags: ['life_host'] },
      });
    }
    const learn: Effect = { kind: 'flag', flag: 'life_' + style.skill };
    events.push(scene(branch + '_solo', style.soloNext + ' · ' + story.title,
      `${consequence} คราวนี้ทุกคนมาหาคุณโดยตรง คุณจะปิดงานนี้อย่างไร?`, [
        choice('เก็บค่าตอบแทนรอบสุดท้าย', 'ผู้จัดโอนเงินปิดงานตามนัด', [{ kind: 'add', stat: 'cleanCash', value: 520 }]),
        choice('ขอฝึกงานแทนการรับเงิน · ' + style.name, 'ผู้จัดให้คุณลองทำงานด้วยตัวเองจนจบ คุณเก็บประสบการณ์ครั้งนี้ไว้', [learn, { kind: 'add', stat: 'fame', value: 2 }]),
      ]));
    events.push(scene(branch + '_crew', style.crewNext + ' · ' + story.title,
      `ทีมส่งข่าวจากงาน “${story.title}” ว่า “${consequence}” ตอนปิดงาน คุณอยากขอบคุณทีมอย่างไร?`, [
        choice('ยกเครดิตให้ทีม ฝากเขาดูแลงานครั้งหน้า', 'ทีมรับหน้าที่ต่อ คุณได้ฝึกการส่งต่องาน', [learn, { kind: 'loyalty', value: 4 }]),
        choice('ประกาศชื่อทุกคนพร้อมแบ่งรายได้', 'รายชื่อทุกคนอยู่ท้ายประกาศ ส่วนแบ่งของคุณเข้ากระเป๋า', [{ kind: 'add', stat: 'cleanCash', value: 260 }, { kind: 'add', stat: 'fame', value: 2 }]),
      ]));
  });
  if (story.fromDay >= 31) {
    open.push({ ...choice('ใช้ประสบการณ์สัญญาจ้าง เปิดรอบที่มีค่าตัวแน่นอน', 'คุณได้ค่าจองล่วงหน้าและสิทธิ์รับงานต่อ', [{ kind: 'add', stat: 'cleanCash', value: 680 }, next(root + '_contract')]), requires: { flags: ['life_contract'] } });
  }
  if (story.fromDay >= 61) {
    open.push({ ...choice('ให้ทีมออกหน้า แล้วค่อยตกลงเรื่องส่วนแบ่ง', 'ทีมออกหน้าแทน คุณได้พัก ส่วนเรื่องรายได้ค่อยคุยกันตอนปิดงาน', [{ kind: 'add', stat: 'heat', value: -5 }, next(root + '_mentor_crew')]), requires: { flags: ['life_mentor'] } });
  }
  return [scene(root, story.title, story.problem, open), ...events];
}

export const lifeStories = stories.flatMap(episodes);

