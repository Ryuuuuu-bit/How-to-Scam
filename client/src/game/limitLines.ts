const banned = ['เฮียใหญ่สั่งห้ามแตะงานนี้วันนี้ ใครฝ่าฝืนเจอดี', 'ข้อเสนอวันนี้ล็อกงานนี้ไว้ เฮียบอกว่า "ทำตามดีลก่อน"'];

const pick = (lines: readonly string[], key: number) =>
  lines[Math.abs(key) % lines.length] ?? lines[0] ?? '';

export function limitLine(
  kind: 'cooldown' | 'banned',
  methodId: string,
  day: number,
  untilDay?: number,
): string {
  if (kind === 'banned') return pick(banned, day + methodId.length);
  const line = pick(cooldown[methodId] ?? generic, day + methodId.length);
  return untilDay ? `${line} · กลับมาทำได้วันที่ ${untilDay + 1}` : line;
}
